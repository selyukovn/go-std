package std

import (
	"fmt"
)

// ---------------------------------------------------------------------------------------------------------------------
// Struct
// ---------------------------------------------------------------------------------------------------------------------

type ErrorCancelled struct {
	msg string
}

// ---------------------------------------------------------------------------------------------------------------------
// Create
// ---------------------------------------------------------------------------------------------------------------------

// NewErrorCancelledFf
//
// Panics in case of empty arguments:
//   - msg
func NewErrorCancelledFf(msg string, msgArgs ...any) ErrorCancelled {
	if msg == "" {
		panic("`msg` must not be empty")
	}

	return ErrorCancelled{msg: fmt.Sprintf(msg, msgArgs...)}
}

// ---------------------------------------------------------------------------------------------------------------------
// State
// ---------------------------------------------------------------------------------------------------------------------

func (e ErrorCancelled) Error() string {
	return e.msg
}

