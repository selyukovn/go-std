package std

// ---------------------------------------------------------------------------------------------------------------------

func Ternary[T any](condition bool, rTrue T, rFalse T) T {
	if condition {
		return rTrue
	} else {
		return rFalse
	}
}

// ---------------------------------------------------------------------------------------------------------------------

func PtrVal[T any](p *T, nilVal T) T {
	if p == nil {
		return nilVal
	}

	return *p
}

